#!/usr/bin/env bash
# ============================================================================
#  GFS - shared environment + helpers (Linux)
#  Sourced by every script in bin/ :  . "$SCRIPT_DIR/env.sh"
#
#  This is the ONLY place to change ports, credentials and folder locations.
#  Values may also be pre-set in the calling shell, e.g.
#      SERVER_PORT=9090 bin/start.sh
#      DATA_DIR=/data/gfs bin/start.sh
#
#  The default port 80 and the bundled mysqld require root (mysqld refuses to
#  run as root unless --user=root is passed, which mysql_args() does).
#
#  Runtime archives under lib/runtime/ are extracted into lib/{jdk,mysql,redis}
#  on first use, so symlinks and executable bits inside them survive.
# ============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PKG_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

LIB_DIR="$PKG_ROOT/lib"
CONF_DIR="$PKG_ROOT/conf"
SQL_DIR="$PKG_ROOT/sql"
RUNTIME_DIR="$LIB_DIR/runtime"

: "${DATA_DIR:=$PKG_ROOT/data}"
: "${LOG_DIR:=$PKG_ROOT/logs}"
: "${STORAGE_DIR:=$PKG_ROOT/storage}"

JAVA_HOME="$LIB_DIR/jdk"
MYSQL_HOME="$LIB_DIR/mysql"
REDIS_HOME="$LIB_DIR/redis"
JAR_FILE="$LIB_DIR/fs-admin.jar"
JAVA_EXE="$JAVA_HOME/bin/java"
MYSQLD_EXE="$MYSQL_HOME/bin/mysqld"
MYSQL_CLI="$MYSQL_HOME/bin/mysql"
MYSQLADMIN="$MYSQL_HOME/bin/mysqladmin"
MY_CNF="$CONF_DIR/my.cnf"
REDIS_CONF="$CONF_DIR/redis.conf"
DB_INIT_FLAG="$DATA_DIR/mysql/.gfs-initialized"

# ---- tunables --------------------------------------------------------------
: "${SERVER_PORT:=80}"
: "${MYSQL_HOST:=127.0.0.1}"
: "${MYSQL_PORT:=3306}"
: "${MYSQL_DB:=gfs}"
: "${MYSQL_USER:=root}"
: "${MYSQL_PASSWORD:=root}"
: "${REDIS_HOST:=127.0.0.1}"
: "${REDIS_PORT:=6379}"
: "${REDIS_PASSWORD:=}"
: "${INNODB_POOL:=256M}"
: "${JAVA_OPTS:=-Xms512m -Xmx1024m}"
: "${FS_FRONTEND_DOMAIN:=http://localhost:$SERVER_PORT}"
: "${GFS_SERVICE_NAME:=gfs}"

# JVM max-memory file shared with the application (see JvmMemoryServiceImpl).
# The file's parent directory also holds the restart flag.
: "${GFS_JVM_CONF:=$CONF_DIR/jvm-xmx.conf}"
GFS_JVM_FLAG="$(dirname "$GFS_JVM_CONF")/jvm-restart.flag"

# exported for conf/application-prod.yml, which resolves ${GFS_HOME},
# ${GFS_DATA_DIR} and ${GFS_STORAGE_DIR} instead of relying on the JVM's
# working directory.
export GFS_HOME="$PKG_ROOT"
export GFS_DATA_DIR="$DATA_DIR"
export GFS_STORAGE_DIR="$STORAGE_DIR"
export GFS_JVM_CONF
export SERVER_PORT MYSQL_HOST MYSQL_PORT MYSQL_DB MYSQL_USER MYSQL_PASSWORD
export REDIS_HOST REDIS_PORT REDIS_PASSWORD
export FS_FRONTEND_DOMAIN

MYSQLD_ARGS=()
SPRING_ARGS=()
JVM_MEM_OPTS=""

# The bundled cache service is Valkey (Redis protocol compatible, official
# prebuilt). Fall back to real redis binaries if someone swaps lib/redis.
set_redis_paths() {
    if [ -x "$REDIS_HOME/bin/valkey-server" ]; then
        REDIS_SERVER="$REDIS_HOME/bin/valkey-server"
        REDIS_CLI="$REDIS_HOME/bin/valkey-cli"
    else
        REDIS_SERVER="$REDIS_HOME/bin/redis-server"
        REDIS_CLI="$REDIS_HOME/bin/redis-cli"
    fi
}
set_redis_paths

# ----------------------------------------------------------------------------
ensure_dirs() {
    mkdir -p "$DATA_DIR/mysql" "$DATA_DIR/redis" "$DATA_DIR/upload" \
        "$LOG_DIR" "$STORAGE_DIR" "$CONF_DIR"
}

# ----------------------------------------------------------------------------
# (Re)generate conf/my.cnf and conf/redis.conf. They are machine generated,
# but only when missing - hand edits survive until the file is deleted.
ensure_configs() {
    ensure_dirs

    if [ ! -f "$MY_CNF" ]; then
        echo "Generating $MY_CNF"
        cat > "$MY_CNF" <<EOF
# AUTO-GENERATED by bin/env.sh - delete this file to regenerate.
# port / basedir / datadir / log-error are supplied on the command line by
# the scripts in bin/, so they are intentionally absent here.
[mysqld]
character-set-server=utf8mb4
collation-server=utf8mb4_general_ci
default-time-zone='+08:00'
default_storage_engine=InnoDB
max_connections=300
max_connect_errors=1000
innodb_buffer_pool_size=$INNODB_POOL
innodb_flush_log_at_trx_commit=2
slow_query_log=0
loose-mysqlx=OFF
sql_mode='STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION'

[mysql]
default-character-set=utf8mb4

[client]
default-character-set=utf8mb4
EOF
    fi

    if [ ! -f "$REDIS_CONF" ]; then
        echo "Generating $REDIS_CONF"
        {
            echo "# AUTO-GENERATED by bin/env.sh - delete this file to regenerate."
            echo "port $REDIS_PORT"
            echo "bind 127.0.0.1 -::1"
            echo "protected-mode yes"
            echo "daemonize no"
            echo "databases 16"
            echo "dir $DATA_DIR/redis"
            echo "logfile $LOG_DIR/redis.log"
            echo "save 900 1"
            echo "save 300 10"
            echo "save 60 10000"
            echo "appendonly no"
            echo "maxmemory-policy noeviction"
            if [ -n "$REDIS_PASSWORD" ]; then
                echo "requirepass $REDIS_PASSWORD"
            fi
        } > "$REDIS_CONF"
    fi
}

# ----------------------------------------------------------------------------
_extract_archive() {
    local name="$1" archive="$2" dest="$LIB_DIR/$1"
    if [ ! -f "$archive" ]; then
        echo "[ERROR] runtime archive missing: $archive"
        return 1
    fi
    if ! command -v tar >/dev/null 2>&1; then
        echo "[ERROR] tar is required to unpack $archive"
        return 1
    fi
    echo "[setup ] extracting $(basename "$archive") -> lib/$name/"
    mkdir -p "$dest"
    find "$dest" -mindepth 1 -maxdepth 1 -exec rm -rf {} +
    case "$archive" in
        *.tar.xz)
            if ! command -v xz >/dev/null 2>&1; then
                echo "[ERROR] xz is required to unpack $archive"
                echo "        Debian/Ubuntu: apt install -y xz-utils"
                echo "        RHEL/Rocky:    dnf install -y xz"
                return 1
            fi
            tar -xJf "$archive" -C "$dest" --strip-components=1
            ;;
        *)
            tar -xzf "$archive" -C "$dest" --strip-components=1
            ;;
    esac
}

ensure_runtimes() {
    if [ ! -x "$JAVA_EXE" ]; then
        _extract_archive jdk "$RUNTIME_DIR/jdk.tar.gz" || return 1
    fi
    if [ ! -x "$MYSQLD_EXE" ]; then
        _extract_archive mysql "$RUNTIME_DIR/mysql.tar.xz" || return 1
    fi
    if [ ! -x "$REDIS_HOME/bin/valkey-server" ] && [ ! -x "$REDIS_HOME/bin/redis-server" ]; then
        _extract_archive redis "$RUNTIME_DIR/valkey.tar.gz" || return 1
    fi
    set_redis_paths
}

# Shared libraries the bundled binaries cannot ship themselves.
check_system_libs() {
    local rc=0 missing

    if ! command -v ldd >/dev/null 2>&1; then
        echo "[WARN  ] ldd not found - skipping shared library check"
        return 0
    fi

    if [ -x "$MYSQLD_EXE" ]; then
        missing="$(ldd "$MYSQLD_EXE" 2>/dev/null | awk '/not found/{print $1}' | sort -u | tr '\n' ' ')"
        if [ -n "$missing" ]; then
            echo "[ERROR] mysqld is missing system libraries: $missing"
            echo "        Debian/Ubuntu: apt install -y libaio1 libnuma1"
            echo "        RHEL/Rocky:    dnf install -y libaio numactl-libs"
            rc=1
        fi
    fi

    if [ -x "$REDIS_SERVER" ]; then
        missing="$(ldd "$REDIS_SERVER" 2>/dev/null | awk '/not found/{print $1}' | sort -u | tr '\n' ' ')"
        if [ -n "$missing" ]; then
            echo "[ERROR] cache service is missing system libraries: $missing"
            echo "        Requires glibc >= 2.34, OpenSSL 3 and systemd-libs"
            echo "        Debian/Ubuntu: apt install -y libssl3 libsystemd0"
            echo "        RHEL/Rocky:    dnf install -y openssl-libs systemd-libs"
            rc=1
        fi
    fi
    return $rc
}

check_binaries() {
    local missing=0
    if [ ! -x "$JAVA_EXE" ]; then echo "   missing  lib/jdk/bin/java"; missing=1; fi
    if [ ! -x "$MYSQLD_EXE" ]; then echo "   missing  lib/mysql/bin/mysqld"; missing=1; fi
    if [ ! -x "$MYSQL_CLI" ]; then echo "   missing  lib/mysql/bin/mysql"; missing=1; fi
    if [ ! -x "$REDIS_SERVER" ]; then echo "   missing  lib/redis/bin/valkey-server"; missing=1; fi
    if [ ! -f "$JAR_FILE" ]; then echo "   missing  lib/fs-admin.jar"; missing=1; fi
    if [ ! -f "$SQL_DIR/init.sql" ]; then echo "   missing  sql/init.sql"; missing=1; fi
    if [ "$missing" -eq 1 ]; then
        echo "[ERROR] The deployment package is incomplete."
        echo "        Restore lib/ and sql/ from the original archive."
        return 1
    fi
}

# ----------------------------------------------------------------------------
mysql_args() {
    MYSQLD_ARGS=(
        --defaults-file="$MY_CNF"
        --basedir="$MYSQL_HOME"
        --datadir="$DATA_DIR/mysql"
        --port="$MYSQL_PORT"
        --bind-address=127.0.0.1
        # own socket path so a system-installed mysqld's /tmp/mysql.sock
        # cannot get in the way
        --socket="$DATA_DIR/mysql/mysql.sock"
        --log-error="$LOG_DIR/mysql.log"
    )
    if [ "$(id -u)" -eq 0 ]; then
        MYSQLD_ARGS+=(--user=root)
    fi
}

spring_args() {
    SPRING_ARGS=(
        --spring.config.additional-location="file:$CONF_DIR/application.yml,file:$CONF_DIR/application-prod.yml"
        --server.port="$SERVER_PORT"
        --fs.frontend.domain="$FS_FRONTEND_DOMAIN"
    )
}

# ----------------------------------------------------------------------------
# %1 = tcp port ; prints the listening PID (empty when nothing is listening
# or when the caller may not inspect other users' sockets)
port_pid() {
    local port="$1" pid=""
    if command -v ss >/dev/null 2>&1; then
        pid="$(ss -lntp 2>/dev/null | awk -v p=":$port" '$4 ~ p"$" {print $NF}' \
            | sed -n 's/.*pid=\([0-9]\+\).*/\1/p' | head -n1)"
    fi
    if [ -z "$pid" ] && command -v lsof >/dev/null 2>&1; then
        pid="$(lsof -nP -t -iTCP:"$port" -sTCP:LISTEN 2>/dev/null | head -n1)"
    fi
    printf '%s' "$pid"
}

port_listening() {
    local port="$1"
    if command -v ss >/dev/null 2>&1; then
        ss -H -lnt 2>/dev/null | awk -v p=":$port" '$4 ~ p"$" {found=1} END{exit found?0:1}'
    elif command -v netstat >/dev/null 2>&1; then
        netstat -lnt 2>/dev/null | awk -v p=":$port" '$4 ~ p"$" {found=1} END{exit found?0:1}'
    elif command -v lsof >/dev/null 2>&1; then
        lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1
    else
        # Without ss/netstat/lsof the bind itself will report the conflict.
        return 1
    fi
}

# Only touch processes that live inside this package directory.
pid_is_ours() {
    local pid="$1"
    if [ -z "$pid" ] || [ ! -r "/proc/$pid/cmdline" ]; then
        return 1
    fi
    tr '\0' ' ' < "/proc/$pid/cmdline" | grep -Fq -- "$PKG_ROOT"
}

wait_port() {
    local port="$1" timeout="${2:-60}" i=0
    while [ "$i" -lt "$timeout" ]; do
        if port_listening "$port"; then return 0; fi
        sleep 1
        i=$((i + 1))
    done
    return 1
}

wait_port_free() {
    local port="$1" timeout="${2:-30}" i=0
    while [ "$i" -lt "$timeout" ]; do
        if ! port_listening "$port"; then return 0; fi
        sleep 1
        i=$((i + 1))
    done
    return 1
}

wait_pid_free() {
    local pid="$1" timeout="${2:-60}" i=0
    while [ "$i" -lt "$timeout" ]; do
        if ! kill -0 "$pid" 2>/dev/null; then return 0; fi
        sleep 1
        i=$((i + 1))
    done
    return 1
}

# reads integer MB from $1 into JVM_MEM_OPTS
#  - valid value N   -> "-Xms<N>m -Xmx<N>m"  (Xms=Xmx so the JVM resizes the
#    heap from the start instead of greedily keeping a large committed heap)
#  - missing/invalid -> empty (caller then uses JAVA_OPTS as-is)
read_xmx() {
    local file="$1" value
    JVM_MEM_OPTS=""
    [ -f "$file" ] || return 0
    value="$(head -n1 "$file" | tr -d '[:space:]')"
    case "$value" in
        ''|*[!0-9]*) return 0 ;;
    esac
    JVM_MEM_OPTS="-Xms${value}m -Xmx${value}m"
}

require_root() {
    if [ "$(id -u)" -ne 0 ]; then
        echo "[ERROR] root privileges are required for this operation."
        echo "        Re-run with: sudo $0 $*"
        return 1
    fi
}

# ----------------------------------------------------------------------------
# Starters / stoppers shared by start.sh, stop.sh and service-run.sh.
# Each component is identified by its port and verified to belong to this
# package before it is touched.
start_redis_bg() {
    local pid
    if port_listening "$REDIS_PORT"; then
        pid="$(port_pid "$REDIS_PORT")"
        if [ -n "$pid" ] && ! pid_is_ours "$pid"; then
            echo "[redis ] FAILED - port $REDIS_PORT is used by PID $pid (not this package)"
            return 1
        fi
        echo "[redis ] already running - port $REDIS_PORT${pid:+, PID $pid}"
        return 0
    fi
    echo "[redis ] starting ..."
    nohup "$REDIS_SERVER" "$REDIS_CONF" >> "$LOG_DIR/redis-console.log" 2>&1 &
    if wait_port "$REDIS_PORT" 20; then
        echo "[redis ] up on port $REDIS_PORT"
        return 0
    fi
    echo "[redis ] FAILED to start. See $LOG_DIR/redis.log"
    return 1
}

start_mysql_bg() {
    local pid
    if port_listening "$MYSQL_PORT"; then
        pid="$(port_pid "$MYSQL_PORT")"
        if [ -n "$pid" ] && ! pid_is_ours "$pid"; then
            echo "[mysql ] FAILED - port $MYSQL_PORT is used by PID $pid (not this package)"
            return 1
        fi
        echo "[mysql ] already running - port $MYSQL_PORT${pid:+, PID $pid}"
        return 0
    fi
    echo "[mysql ] starting ..."
    mysql_args
    nohup "$MYSQLD_EXE" "${MYSQLD_ARGS[@]}" >> "$LOG_DIR/mysql-console.log" 2>&1 &
    if wait_port "$MYSQL_PORT" 60; then
        echo "[mysql ] up on port $MYSQL_PORT"
        return 0
    fi
    echo "[mysql ] FAILED to start. See $LOG_DIR/mysql.log"
    return 1
}

stop_app() {
    local pid
    if ! port_listening "$SERVER_PORT"; then
        echo "[app   ] not running on port $SERVER_PORT"
        return 0
    fi
    pid="$(port_pid "$SERVER_PORT")"
    if [ -z "$pid" ]; then
        echo "[app   ] port $SERVER_PORT is in use but its PID is not visible - run as root"
        return 1
    fi
    if ! pid_is_ours "$pid"; then
        echo "[app   ] port $SERVER_PORT is used by an unrelated PID $pid - left alone"
        return 1
    fi
    echo "[app   ] stopping PID $pid ..."
    if [ "$FORCE" = "1" ]; then
        kill -KILL "$pid" 2>/dev/null || true
    else
        kill -TERM "$pid" 2>/dev/null || true
        if ! wait_port_free "$SERVER_PORT" 30; then
            echo "[app   ] still listening after 30s - forcing it down"
            kill -KILL "$pid" 2>/dev/null || true
        fi
    fi
    echo "[app   ] stopped"
}

stop_redis() {
    local pid
    if ! port_listening "$REDIS_PORT"; then
        echo "[redis ] not running on port $REDIS_PORT"
        return 0
    fi
    pid="$(port_pid "$REDIS_PORT")"
    if [ -z "$pid" ]; then
        echo "[redis ] port $REDIS_PORT is in use but its PID is not visible - run as root"
        return 1
    fi
    if ! pid_is_ours "$pid"; then
        echo "[redis ] port $REDIS_PORT is used by an unrelated PID $pid - left alone"
        return 1
    fi
    echo "[redis ] stopping PID $pid ..."
    if [ "$FORCE" = "1" ]; then
        kill -KILL "$pid" 2>/dev/null || true
    else
        if [ -n "$REDIS_PASSWORD" ]; then
            "$REDIS_CLI" -h 127.0.0.1 -p "$REDIS_PORT" -a "$REDIS_PASSWORD" --no-auth-warning shutdown >/dev/null 2>&1 || true
        else
            "$REDIS_CLI" -h 127.0.0.1 -p "$REDIS_PORT" shutdown >/dev/null 2>&1 || true
        fi
        if ! wait_pid_free "$pid" 15; then
            echo "[redis ] still running after 15s - forcing it down"
            kill -KILL "$pid" 2>/dev/null || true
        fi
    fi
    echo "[redis ] stopped"
}

stop_mysql() {
    local pid
    if ! port_listening "$MYSQL_PORT"; then
        echo "[mysql ] not running on port $MYSQL_PORT"
        return 0
    fi
    pid="$(port_pid "$MYSQL_PORT")"
    if [ -z "$pid" ]; then
        echo "[mysql ] port $MYSQL_PORT is in use but its PID is not visible - run as root"
        return 1
    fi
    if ! pid_is_ours "$pid"; then
        echo "[mysql ] port $MYSQL_PORT is used by an unrelated PID $pid - left alone"
        return 1
    fi
    echo "[mysql ] stopping PID $pid ..."
    if [ "$FORCE" = "1" ]; then
        kill -KILL "$pid" 2>/dev/null || true
    else
        "$MYSQLADMIN" -u "$MYSQL_USER" -p"$MYSQL_PASSWORD" -h 127.0.0.1 \
            --protocol=TCP -P "$MYSQL_PORT" shutdown >/dev/null 2>&1 || true
        if ! wait_pid_free "$pid" 60; then
            echo "[mysql ] still running after 60s - forcing it down"
            kill -KILL "$pid" 2>/dev/null || true
        fi
    fi
    wait_port_free "$MYSQL_PORT" 15 || true
    echo "[mysql ] stopped"
}
